import type { Accent } from "@/components/ui/AccentCard";

export interface Member {
  name: string;
  role: string;
  telegram: string | null;
}

export type Responsibility = string | { text: string; items: string[] };

export interface Project {
  title?: string | null;
  description?: string | null;
  metric?: string | null;
  image?: string | null;
}

export interface DepartmentData {
  slug: string;
  name: string;
  accent: Accent;
  gradient: string;
  glow: [string, string];
  cover: string | null;
  memberCount: number | null;
  slogan: string | null;
  about: string[] | null;
  responsibilities: Responsibility[] | null;
  headQuote: string | null;
  team: Member[] | null;
  subDepartments: { name: string; description: string }[] | null;
  projects: Project[] | null;
  faq: { question: string; answer: string }[] | null;
}

interface DeptInput {
  slug: string;
  name: string;
  accent: Accent;
  gradient: string;
  glow: [string, string];
  cover?: string | null;
  memberCount?: number | null;
  slogan?: string | null;
  about?: string[] | null;
  responsibilities?: Responsibility[] | null;
  headQuote?: string | null;
  team?: Member[] | null;
  subDepartments?: { name: string; description: string }[] | null;
  projects?: Project[] | null;
  faq?: { question: string; answer: string }[] | null;
}

function dept(input: DeptInput): DepartmentData {
  return {
    slug: input.slug,
    name: input.name,
    accent: input.accent,
    gradient: input.gradient,
    glow: input.glow,
    cover: input.cover ?? null,
    memberCount: input.memberCount ?? null,
    slogan: input.slogan ?? null,
    about: input.about ?? null,
    responsibilities: input.responsibilities ?? null,
    headQuote: input.headQuote ?? null,
    team: input.team ?? null,
    subDepartments: input.subDepartments ?? null,
    projects: input.projects ?? null,
    faq: input.faq ?? null,
  };
}

